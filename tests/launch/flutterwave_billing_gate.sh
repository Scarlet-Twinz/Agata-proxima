#!/usr/bin/env bash
set -euo pipefail

production="crates/proxima-control-plane/src/production.rs"
main="crates/proxima-control-plane/src/main.rs"
migration="crates/proxima-control-plane/migrations/0022_flutterwave_billing.sql"
react_ui="frontend/src/pages/console/NestedResource.tsx"
embedded_ui="crates/proxima-control-plane/web/app.html"

test -f "$migration"
grep -Fq 'fn flutterwave_plan_id' "$production"
grep -Fq 'configured_flutterwave_plans_unique' "$production"
grep -Fq 'configured_flutterwave_amounts' "$production"
grep -Fq 'fn flutterwave_enabled()' "$production"
grep -Fq 'FLUTTERWAVE_SECRET_KEY' "$production"
grep -Fq 'FLUTTERWAVE_WEBHOOK_SECRET_HASH' "$production"
grep -Fq 'FLUTTERWAVE_ENVIRONMENT' "$production"
grep -Fq 'FLUTTERWAVE_STARTER_PLAN_ID' "$production"
grep -Fq 'FLUTTERWAVE_GROWTH_PLAN_ID' "$production"
grep -Fq 'FLUTTERWAVE_SCALE_PLAN_ID' "$production"
grep -Fq 'FLUTTERWAVE_STARTER_AMOUNT_USD' "$production"
grep -Fq 'FLUTTERWAVE_GROWTH_AMOUNT_USD' "$production"
grep -Fq 'FLUTTERWAVE_SCALE_AMOUNT_USD' "$production"
grep -Fq 'verify_flutterwave_hash' "$production"
grep -Fq 'headers.get("verif-hash")' "$production"
grep -Fq 'verify_flutterwave_transaction' "$production"
grep -Fq 'https://api.flutterwave.com/v3/payments' "$production"
grep -Fq 'https://api.flutterwave.com/v3/transactions/' "$production"
grep -Fq "provider='flutterwave'" "$production"
grep -Fq 'checkout_url' "$production"
grep -Fq '"currency":"USD"' "$production"
grep -Fq '"/api/v1/webhooks/flutterwave"' "$main"
grep -Fq '0022_flutterwave_billing.sql' "$main"
grep -Fq "provider='flutterwave'" "$migration"
grep -Fq 'Flutterwave did not return a secure hosted checkout URL' "$react_ui"
grep -Fq 'BILLING · FLUTTERWAVE' "$react_ui"
grep -Fq 'location.href=d.checkout_url' "$embedded_ui"
grep -Fq 'Flutterwave subscription' "$embedded_ui"
! grep -Eiq 'Paddle|paddle\.com|client_token' "$production" "$react_ui" "$embedded_ui"
! grep -Eiq 'LEMON_SQUEEZY_|PAYSTACK_|STRIPE_' "$production"
! grep -Eiq 'FLUTTERWAVE_SECRET_KEY\s*=\s*[^[:space:]]' "$production"

echo "PASS: Flutterwave plan configuration, USD pricing contract, hosted checkout, transaction verification, webhook signature, migration, and UI wiring"
